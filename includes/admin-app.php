<?php
/**
 * The design editor: a full-screen admin page built with @wordpress/build
 * (routes/editor → build/), booted by core's @wordpress/boot. It's the one
 * screen in the editor's style; lists and settings stay classic admin
 * screens, like CampTix's.
 *
 * The page hides the admin menu and bar (like the block editor's full-screen
 * mode) and leaves the whole window to the canvas and its floating Dock.
 *
 * @package EventsCertificate
 */

namespace EventsCertificate\AdminApp;

use EventsCertificate\Admin;
use EventsCertificate\Designs;

defined( 'ABSPATH' ) || exit;

/**
 * Page slug (wp-build's page id + "-wp-admin").
 */
const SLUG = 'evcert-editor-wp-admin';

/**
 * The page's render callback, generated by @wordpress/build.
 */
const RENDER = 'evcert_evcert_editor_wp_admin_render_page';

/**
 * Registers the hooks, when the editor was built.
 */
function bootstrap() {
	$build = dirname( __DIR__ ) . '/build/build.php';
	if ( ! is_file( $build ) ) {
		return;
	}
	require_once $build;

	add_action( 'admin_menu', __NAMESPACE__ . '\add_page' );
	add_action( 'load-admin_page_' . SLUG, __NAMESPACE__ . '\set_title' );
	add_action( 'admin_enqueue_scripts', __NAMESPACE__ . '\enqueue' );
	add_filter( 'admin_body_class', __NAMESPACE__ . '\body_class' );
	add_action( 'evcert_certificates_screen', __NAMESPACE__ . '\render_editor_link', 5 );
}

/**
 * The file of the @wordpress/boot module asset the site provides: the
 * Gutenberg plugin's when active (it replaces core's module), else core's
 * (WordPress 7.0+).
 *
 * @return string Path, or '' when there is none.
 */
function boot_asset_file() {
	$files = array( ABSPATH . WPINC . '/js/dist/script-modules/boot/index.min.asset.php' );
	if ( defined( 'GUTENBERG_VERSION' ) ) {
		array_unshift( $files, WP_PLUGIN_DIR . '/gutenberg/build/modules/boot/index.min.asset.php' );
	}
	foreach ( $files as $file ) {
		if ( is_file( $file ) ) {
			return $file;
		}
	}

	return '';
}

/**
 * The @wordpress/boot asset (dependencies, version), for the page generated
 * by @wordpress/build (build/modules/boot/index.min.asset.php returns it).
 *
 * @return array{dependencies: string[], version: string|false}
 */
function boot_asset() {
	$file  = boot_asset_file();
	$asset = '' === $file ? null : require $file;

	return is_array( $asset ) ? $asset : array(
		'dependencies' => array(),
		'version'      => false,
	);
}

/**
 * Whether the editor can run (it was built).
 *
 * @return bool
 */
function available() {
	return function_exists( RENDER );
}

/**
 * The editor's URL for a design.
 *
 * @param int $design Design post ID.
 * @return string
 */
function url( $design ) {
	return add_query_arg(
		array(
			'page'   => SLUG,
			'design' => (int) $design,
		),
		admin_url( 'admin.php' )
	);
}

/**
 * Registers the page with no menu item: it opens from the Certificates
 * screen.
 */
function add_page() {
	if ( available() ) {
		add_submenu_page( '', __( 'Certificate design', 'events-certificate' ), '', Admin\CAPABILITY, SLUG, RENDER );
	}
}

/**
 * The browser tab title, like the block editor's: "Edit certificate ‹ Site
 * name — WordPress". A page with no menu item has no title of its own, and
 * core builds the tab title from the $title global.
 */
function set_title() {
	$GLOBALS['title'] = __( 'Edit certificate', 'events-certificate' ); // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited -- core reads the screen title from $title.
}

/**
 * Whether the current screen is the editor.
 *
 * @return bool
 */
function is_editor_screen() {
	return isset( $_GET['page'] ) && SLUG === $_GET['page']; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- only reads which screen this is.
}

/**
 * Full-screen body class on the editor.
 *
 * @param string $classes Body classes.
 * @return string
 */
function body_class( $classes ) {
	return is_editor_screen() ? $classes . ' evcert-editor-screen' : $classes;
}

/**
 * The editor's full-screen styles, its fonts and its data: the design to edit
 * (created from Base the first time) and where to go back.
 */
function enqueue() {
	if ( ! is_editor_screen() ) {
		return;
	}
	$url = plugins_url( '', __DIR__ . '/../events-certificate.php' );
	wp_enqueue_style( 'evcert-editor-screen', $url . '/assets/editor-screen.css', array(), \EventsCertificate\VERSION );
	wp_add_inline_style( 'evcert-editor-screen', fonts_css( $url . '/fonts' ) );

	$design = isset( $_GET['design'] ) ? absint( $_GET['design'] ) : 0; // phpcs:ignore WordPress.Security.NonceVerification.Recommended -- which design to open; editing goes through the REST API with its own nonce.
	if ( ! $design || Designs\POST_TYPE !== get_post_type( $design ) ) {
		$design = Designs\site_design_id();
	}
	wp_register_script( 'evcert-editor-data', false, array(), \EventsCertificate\VERSION, false );
	wp_enqueue_script( 'evcert-editor-data' );
	wp_add_inline_script(
		'evcert-editor-data',
		'window.evcertEditor = ' . wp_json_encode(
			array(
				'design'  => $design,
				'exitUrl' => menu_page_url( Admin\SLUG, false ),
				'fonts'   => $url . '/fonts',
				'sample'  => array(
					'name'        => 'Mary Anne Sue',
					'event'       => get_bloginfo( 'name' ),
					'location'    => 'São Paulo, Brazil',
					'date_iso'    => gmdate( 'Y-m-d\TH:i:s\Z' ),
					'date_site'   => wp_date( (string) get_option( 'date_format' ) ),
					'hours'       => '8',
					/* translators: %s: number of hours, in the certificate design's sample. */
					'hours_long'  => sprintf( _n( '%s hour', '%s hours', 8, 'events-certificate' ), '8' ),
					'role'        => __( 'Speaker', 'events-certificate' ),
					'details'     => __( 'Building accessible blocks', 'events-certificate' ),
					'document'    => 'CPF •••.•••.789-••',
					'signer_name' => wp_get_current_user()->display_name,
					'signer_role' => __( 'Event Coordinator', 'events-certificate' ),
					'code'        => '2611-04K7-M29Q-XAP3',
					'verify_url'  => untrailingslashit( preg_replace( '#^https?://#', '', home_url( \EventsCertificate\Settings\value( 'slug' ) ) ) ),
				),
			)
		) . ';',
		'before'
	);
}

/**
 * The @font-face rules of the plugin's fonts, for the canvas.
 *
 * @param string $base Fonts folder URL.
 * @return string CSS.
 */
function fonts_css( $base ) {
	$css = '';
	foreach ( array(
		array( 'Lora', 400, 'Lora-Regular' ),
		array( 'Lora', 500, 'Lora-Medium' ),
		array( 'Lora', 600, 'Lora-SemiBold' ),
		array( 'Inter', 400, 'Inter-Regular' ),
		array( 'Inter', 500, 'Inter-Medium' ),
		array( 'Inter', 600, 'Inter-SemiBold' ),
	) as $font ) {
		$css .= sprintf(
			"@font-face{font-family:'%s';font-weight:%d;font-style:normal;font-display:block;src:url('%s/%s.ttf') format('truetype');}\n",
			$font[0],
			$font[1],
			esc_url_raw( $base ),
			$font[2]
		);
	}

	return $css;
}

/**
 * Link to the editor on the Certificates screen.
 */
function render_editor_link() {
	if ( ! available() ) {
		return;
	}
	printf(
		'<p><a class="button button-primary" href="%s">%s</a></p>',
		esc_url( url( Designs\site_design_id() ) ),
		esc_html__( 'Edit certificate design', 'events-certificate' )
	);
}
