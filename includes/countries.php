/**
 * A country's name.
 *
 * @param string $code Code.
 * @return string
 */
function name( $code ) {
	$all = all();

	return $all[ strtoupper( (string) $code ) ] ?? '';
}

/**
 * The country to start with: the site language's region (pt_BR → BR), else none.
 *
 * @return string
 */
function guess() {
	$region = strtoupper( (string) substr( (string) strrchr( determine_locale(), '_' ), 1 ) );

	return isset( all()[ $region ] ) ? $region : '';
}
